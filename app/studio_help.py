def html(key: str) -> str:
    for k, _t, body in CHAPTERS:
        if k == key:
            return CSS + body
    return CSS + CHAPTERS[0][2]


class HelpView(QWidget):
    """Оглавление слева, глава справа. open_ref() — полный справочник EchoScript (если есть)."""

    def __init__(self, open_ref=None, parent=None):
        super().__init__(parent)
        h = QHBoxLayout(self)
        h.setContentsMargins(0, 0, 0, 0)
        h.setSpacing(8)
        self.toc = QListWidget()
        self.toc.setObjectName("HelpToc")
        self.toc.setFixedWidth(190)
        self.toc.setWordWrap(True)
        for k, title, _b in CHAPTERS:
            it = QListWidgetItem(title)
            it.setData(Qt.ItemDataRole.UserRole, k)
            self.toc.addItem(it)
        right = QVBoxLayout()
        self.view = QTextBrowser()
        self.view.setOpenExternalLinks(True)
        self.view.setStyleSheet("QTextBrowser { background: #121018; border: none; border-radius: 10px; padding: 8px; }")
        right.addWidget(self.view, 1)
        nav = QHBoxLayout()
        self.b_prev = QPushButton("← Назад")
        self.b_next = QPushButton("Дальше →")
        self.b_prev.clicked.connect(lambda: self.toc.setCurrentRow(max(0, self.toc.currentRow() - 1)))
        self.b_next.clicked.connect(lambda: self.toc.setCurrentRow(min(self.toc.count() - 1,
                                                                       self.toc.currentRow() + 1)))
        nav.addWidget(self.b_prev)
        nav.addWidget(self.b_next)
        nav.addStretch(1)
        if open_ref is not None:
            ref = QPushButton("Полный справочник EchoScript…")
            ref.clicked.connect(open_ref)
            nav.addWidget(ref)
        right.addLayout(nav)
        h.addWidget(self.toc)
        h.addLayout(right, 1)
        self.toc.currentRowChanged.connect(self._show)
        self.toc.setCurrentRow(0)

    def _show(self, row):
        if 0 <= row < len(CHAPTERS):
            self.view.setHtml(CSS + CHAPTERS[row][2])
            self.view.verticalScrollBar().setValue(0)
            self.b_prev.setEnabled(row > 0)
            self.b_next.setEnabled(row < len(CHAPTERS) - 1)

    def open_chapter(self, key):
        for i, (k, _t, _b) in enumerate(CHAPTERS):
            if k == key:
                self.toc.setCurrentRow(i)
                return


